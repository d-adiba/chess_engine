void merge(int arr[], int left, int mid, int right, board_t *b_t)
{
    int n1 = mid - left + 1;
    int n2 = right - mid;

    int *L = malloc(n1 * sizeof(int));
    int *R = malloc(n2 * sizeof(int));

    for (int i = 0; i < n1; i++)
        L[i] = arr[left + i];

    for (int i = 0; i < n2; i++)
        R[i] = arr[mid + 1 + i];

    int i = 0;
    int j = 0;
    int k = left;

    while (i < n1 && j < n2)
    {
        if (score_move(L[i], b_t) >= score_move(R[j], b_t))
        {
            arr[k++] = L[i++];
        }
        else
        {
            arr[k++] = R[j++];
        }
    }

    while (i < n1)
    {
        arr[k++] = L[i++];
    }

    while (j < n2)
    {
        arr[k++] = R[j++];
    }

    free(L);
    free(R);
}
void merge_sort(int arr[], int left, int right, board_t *b_t)
{
    if (left >= right)
        return;

    int mid = left + (right - left) / 2;

    merge_sort(arr, left, mid, b_t);
    merge_sort(arr, mid + 1, right,b_t);

    merge(arr, left, mid, right,b_t);
}